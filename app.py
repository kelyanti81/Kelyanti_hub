
import os
import re
import secrets
from functools import wraps

import psycopg
from psycopg.rows import dict_row
from psycopg.errors import UniqueViolation

from flask import (
    Flask, render_template, request, redirect,
    url_for, session, flash, abort
)
from werkzeug.security import generate_password_hash, check_password_hash


app = Flask(__name__)
app.secret_key = os.environ.get("SECRET_KEY") or secrets.token_hex(32)

DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()

ADMIN_USERNAME = os.environ.get("HUB_USERNAME", "admin")
ADMIN_PASSWORD = os.environ.get("HUB_PASSWORD", "")

DEFAULT_COLOR = "#8b5cf6"


def connect_db():
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL est absent des variables d'environnement Render."
        )

    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=15
    )


def init_db():
    with connect_db() as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS members (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                grade TEXT NOT NULL DEFAULT 'member',
                active BOOLEAN NOT NULL DEFAULT TRUE,
                display_name TEXT NOT NULL DEFAULT '',
                theme_color TEXT NOT NULL DEFAULT '#8b5cf6'
            )
        """)

        db.execute("""
            ALTER TABLE members
            ADD COLUMN IF NOT EXISTS grade TEXT NOT NULL DEFAULT 'member'
        """)
        db.execute("""
            ALTER TABLE members
            ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE
        """)
        db.execute("""
            ALTER TABLE members
            ADD COLUMN IF NOT EXISTS display_name TEXT NOT NULL DEFAULT ''
        """)
        db.execute("""
            ALTER TABLE members
            ADD COLUMN IF NOT EXISTS theme_color TEXT NOT NULL DEFAULT '#8b5cf6'
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS settings (
                key TEXT PRIMARY KEY,
                value TEXT NOT NULL
            )
        """)


init_db()


def get_setting(key, default=""):
    with connect_db() as db:
        row = db.execute(
            "SELECT value FROM settings WHERE key = %s",
            (key,)
        ).fetchone()

    return row["value"] if row else default


def set_setting(key, value):
    with connect_db() as db:
        db.execute("""
            INSERT INTO settings (key, value)
            VALUES (%s, %s)
            ON CONFLICT(key) DO UPDATE SET value = EXCLUDED.value
        """, (key, value))


def get_member(username):
    with connect_db() as db:
        return db.execute(
            "SELECT * FROM members WHERE username = %s",
            (username,)
        ).fetchone()


def current_user():
    username = session.get("username")

    if not username:
        return None

    if session.get("role") == "admin":
        return {
            "username": ADMIN_USERNAME,
            "display_name": get_setting(
                "admin_display_name", ADMIN_USERNAME
            ),
            "grade": "admin",
            "theme_color": get_setting(
                "admin_theme_color", DEFAULT_COLOR
            ),
            "active": True
        }

    member = get_member(username)

    if not member or not member["active"]:
        session.clear()
        return None

    return member


def login_required(function):
    @wraps(function)
    def wrapper(*args, **kwargs):
        if not current_user():
            return redirect(url_for("login"))
        return function(*args, **kwargs)
    return wrapper


def admin_required(function):
    @wraps(function)
    def wrapper(*args, **kwargs):
        if session.get("role") != "admin":
            abort(403)
        return function(*args, **kwargs)
    return wrapper


def csrf_token():
    if "_csrf_token" not in session:
        session["_csrf_token"] = secrets.token_hex(24)
    return session["_csrf_token"]


@app.context_processor
def inject_globals():
    user = current_user()

    return {
        "current_user": user,
        "csrf_token": csrf_token,
        "display_name": (
            user["display_name"] or user["username"]
            if user else ""
        ),
        "theme_color": (
            user["theme_color"] if user else DEFAULT_COLOR
        ),
        "is_admin": session.get("role") == "admin",
    }


@app.before_request
def protect_forms():
    if request.method == "POST":
        sent = request.form.get("csrf_token", "")
        expected = session.get("_csrf_token", "")

        if (
            not sent
            or not expected
            or not secrets.compare_digest(sent, expected)
        ):
            abort(400)


