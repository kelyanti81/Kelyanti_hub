def init_db():
    with connect_db() as db:
        db.execute("""CREATE TABLE IF NOT EXISTS members (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL,
            password_hash TEXT NOT NULL,
            grade TEXT NOT NULL DEFAULT 'member',
            active BOOLEAN NOT NULL DEFAULT TRUE,
            display_name TEXT NOT NULL DEFAULT '',
            theme_color TEXT NOT NULL DEFAULT '#8b5cf6'
        )""")

        for sql in [
            "ALTER TABLE members ADD COLUMN IF NOT EXISTS grade TEXT NOT NULL DEFAULT 'member'",
            "ALTER TABLE members ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE",
            "ALTER TABLE members ADD COLUMN IF NOT EXISTS display_name TEXT NOT NULL DEFAULT ''",
            "ALTER TABLE members ADD COLUMN IF NOT EXISTS theme_color TEXT NOT NULL DEFAULT '#8b5cf6'",
            "ALTER TABLE members ADD COLUMN IF NOT EXISTS last_seen TIMESTAMPTZ"
        ]:
            db.execute(sql)

        db.execute("""
            CREATE TABLE IF NOT EXISTS settings (
                key TEXT PRIMARY KEY,
                value TEXT NOT NULL
            )
        """)

        db.execute("""CREATE TABLE IF NOT EXISTS dell_status (
            id INTEGER PRIMARY KEY CHECK (id = 1),
            payload JSONB NOT NULL,
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )""")


init_db()


def get_setting(key, default=""):
    with connect_db() as db:
        row = db.execute(
            "SELECT value FROM settings WHERE key=%s",
            (key,)
        ).fetchone()

    return row["value"] if row else default


def set_setting(key, value):
    with connect_db() as db:
        db.execute("""
            INSERT INTO settings(key,value)
            VALUES(%s,%s)
            ON CONFLICT(key)
            DO UPDATE SET value=EXCLUDED.value
        """, (key, value))


def get_admin_settings():
    with connect_db() as db:
        rows = db.execute("""
            SELECT key,value FROM settings
            WHERE key IN ('admin_display_name','admin_theme_color')
        """).fetchall()

    return {r["key"]: r["value"] for r in rows}


def get_member(username):
    with connect_db() as db:
        return db.execute(
            "SELECT * FROM members WHERE username=%s",
            (username,)
        ).fetchone()


def current_user():
    if getattr(g, "_current_user_loaded", False):
        return g._current_user

    g._current_user_loaded = True
    g._current_user = None

    username = session.get("username")

    if not username:
        return None

    if session.get("role") == "admin":
        s = get_admin_settings()

        g._current_user = {
            "username": ADMIN_USERNAME,
            "display_name": s.get("admin_display_name", ADMIN_USERNAME),
            "grade": "admin",
            "theme_color": s.get("admin_theme_color", DEFAULT_COLOR),
            "active": True
        }

        return g._current_user

    member = get_member(username)

    if not member or not member["active"]:
        session.clear()
        return None

    g._current_user = member
    return member


def login_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if not current_user():
            return redirect(url_for("login"))
        return fn(*args, **kwargs)
    return wrapper


def admin_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if session.get("role") != "admin":
            abort(403)
        return fn(*args, **kwargs)
    return wrapper


def csrf_token():
    if "_csrf_token" not in session:
        session["_csrf_token"] = secrets.token_hex(24)
    return session["_csrf_token"]


@app.before_request
def protect_forms():
    # L'agent Dell utilise son propre jeton secret X-Dell-Token.
    if request.method == "POST" and request.path != "/api/dell/heartbeat":
        sent = (
            request.form.get("csrf_token", "")
            or request.headers.get("X-CSRF-Token", "")
        )
        expected = session.get("_csrf_token", "")

        if (
            not sent
            or not expected
            or not secrets.compare_digest(sent, expected)
        ):
            abort(400)


def read_json_setting(key, default):
    try:
        return json.loads(get_setting(key, ""))
    except (TypeError, ValueError):
        return default


def navigation_items():
    raw = read_json_setting("navigation_config", DEFAULT_NAV)

    if not isinstance(raw, list):
        raw = DEFAULT_NAV

    result = []

    for default in DEFAULT_NAV:
        item = next(
            (
                x for x in raw
                if isinstance(x, dict) and x.get("key") == default["key"]
            ),
            {}
        )

        result.append({
            "key": default["key"],
            "label": str(item.get("label", default["label"]))[:32] or default["label"],
            "icon": default["icon"],
            "visible": bool(item.get("visible", default["visible"]))
        })

    return result


@app.context_processor
def inject_globals():
    user = current_user()
    theme = read_json_setting("site_theme", {})

    bg = theme.get("background", "#0c0b13") if isinstance(theme, dict) else "#0c0b13"
    surface = theme.get("surface", "#151421") if isinstance(theme, dict) else "#151421"

    if not re.fullmatch(r"#[0-9a-fA-F]{6}", str(bg)):
        bg = "#0c0b13"

    if not re.fullmatch(r"#[0-9a-fA-F]{6}", str(surface)):
        surface = "#151421"

    nav = [
        x for x in navigation_items()
        if x["visible"] and (
            x["key"] != "members" or session.get("role") == "admin"
        )
    ]

    return {
        "current_user": user,
        "csrf_token": csrf_token,
        "display_name": (user["display_name"] or user["username"]) if user else "",
        "theme_color": user["theme_color"] if user else DEFAULT_COLOR,
        "is_admin": session.get("role") == "admin",
        "navigation_items": nav,
        "site_background": bg,
        "site_surface": surface
    }


